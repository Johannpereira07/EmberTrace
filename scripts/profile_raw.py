#!/usr/bin/env python3
"""
Profile raw FIRMS files (MODIS / VIIRS, NRT or archive) and check them against the
assumptions in AGENTS.md. Reads in chunks, so large files are fine.

Usage:
  python scripts/profile_raw.py "data/raw/**/*.csv" [--out docs/07-data-profile.md]
Share the resulting markdown (NOT the data) with the team.
"""
import argparse, glob, re, sys
from collections import Counter, defaultdict
import numpy as np
import pandas as pd

CATEGORICAL = ["satellite", "instrument", "confidence", "type", "version", "daynight"]
KEY = ["latitude", "longitude", "acq_date", "acq_time"]
KNOWN_SATELLITES = {"T", "A", "TERRA", "AQUA", "N", "NPP", "SNPP", "N20", "NOAA-20", "1", "N21", "NOAA-21", "2"}
EXPECTED_CORE = ["latitude", "longitude", "scan", "track", "acq_date", "acq_time", "satellite",
                 "confidence", "version", "frp", "daynight"]


def profile_file(path):
    cols, nulls, rows, cats = None, Counter(), 0, defaultdict(Counter)
    by_year, sat_year, months, ver_year = Counter(), Counter(), set(), Counter()
    dmin = dmax = None
    lat = [np.inf, -np.inf]; lon = [np.inf, -np.inf]
    time_ok = time_bad = 0
    hashes = []
    for chunk in pd.read_csv(path, dtype=str, chunksize=500_000):
        if cols is None:
            cols = list(chunk.columns)
        rows += len(chunk)
        nulls.update(chunk.isna().sum().to_dict())
        for c in CATEGORICAL:
            if c in chunk:
                cats[c].update(chunk[c].fillna("<null>").value_counts().to_dict())
        d = pd.to_datetime(chunk["acq_date"], errors="coerce")
        dmin = d.min() if dmin is None else min(dmin, d.min())
        dmax = d.max() if dmax is None else max(dmax, d.max())
        by_year.update(d.dt.year.value_counts().to_dict())
        months.update(d.dt.to_period("M").dropna().unique())
        if "version" in chunk:
            ver_year.update(zip(chunk["version"].fillna("<null>"), d.dt.year))
        if "satellite" in chunk:
            sat_year.update(zip(chunk["satellite"].fillna("<null>"), d.dt.year))
        la, lo = pd.to_numeric(chunk["latitude"], errors="coerce"), pd.to_numeric(chunk["longitude"], errors="coerce")
        lat = [min(lat[0], la.min()), max(lat[1], la.max())]; lon = [min(lon[0], lo.min()), max(lon[1], lo.max())]
        ok = chunk["acq_time"].fillna("").str.match(r"^(\d{1,4}|\d{2}:\d{2})$")
        time_ok += int(ok.sum()); time_bad += int((~ok).sum())
        hashes.append(pd.util.hash_pandas_object(chunk[[k for k in KEY if k in chunk]], index=False).values)
    h = np.concatenate(hashes)
    # sensor from SATELLITE names: real VIIRS files use MODIS-style column names
    sats = {x.upper() for x in cats["satellite"]}
    sensor = ("MODIS" if sats & {"TERRA", "AQUA", "T", "A"} else
              "VIIRS" if sats & {"N", "NPP", "SNPP", "N20", "N21", "NOAA-20", "NOAA-21", "1", "2"} else "UNKNOWN")
    return dict(path=path, cols=cols, rows=rows, nulls=nulls, cats=cats, by_year=by_year,
                sat_year=sat_year, months=months, ver_year=ver_year, dmin=dmin, dmax=dmax, lat=lat, lon=lon,
                time_ok=time_ok, time_bad=time_bad, hashes=h, sensor=sensor,
                dup_within=int(len(h) - len(np.unique(h))))


def top(counter, n=8):
    return ", ".join(f"`{k}`: {v:,}" for k, v in counter.most_common(n)) or "none"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("pattern")
    ap.add_argument("--out")
    a = ap.parse_args()
    files = sorted(glob.glob(a.pattern, recursive=True))
    if not files:
        sys.exit(f"no files match {a.pattern}")
    P = [profile_file(f) for f in files]
    L, checks = [], []
    L.append("# Raw data profile\n")
    L.append("Generated by `scripts/profile_raw.py`. Facts below are observed in the files; the checks at the end compare them with AGENTS.md assumptions.\n")
    for p in P:
        L.append(f"## {p['path']}\n")
        L.append(f"- Sensor (from satellite names): **{p['sensor']}**; rows: **{p['rows']:,}**; columns ({len(p['cols'])}): `{', '.join(p['cols'])}`")
        L.append(f"- Dates: {p['dmin'].date()} to {p['dmax'].date()}; lat {p['lat'][0]:.2f} to {p['lat'][1]:.2f}; lon {p['lon'][0]:.2f} to {p['lon'][1]:.2f}")
        nn = {k: v for k, v in p["nulls"].items() if v}
        L.append(f"- Null counts: {nn if nn else 'none'}; duplicate rows (same lat, lon, date, time) inside file: {p['dup_within']:,}")
        for c in CATEGORICAL:
            if c in p["cats"]:
                L.append(f"- `{c}` values: {top(p['cats'][c])}")
        L.append(f"- `acq_time` samples fit HH:MM or HHMM: {p['time_ok']:,} ok, {p['time_bad']:,} not")
        if "type" in p["cats"]:
            tot = sum(p["cats"]["type"].values())
            L.append("- `type` share: " + ", ".join(f"`{k}`: {100*v/tot:.1f}%" for k, v in sorted(p["cats"]["type"].items())))
        if len(p["cats"].get("version", {})) > 1:
            vy = sorted({(v, int(y)) for (v, y) in p["ver_year"] if pd.notna(y)})
            L.append("- `version` by year (more than one version in this file): " + "; ".join(
                f"`{v}`: {min(y for vv, y in vy if vv == v)}-{max(y for vv, y in vy if vv == v)}" for v in sorted({v for v, _ in vy})))
        L.append("- Rows per year: " + ", ".join(f"{int(y)}: {n:,}" for y, n in sorted(p['by_year'].items())) + "\n")
    L.append("## Satellite coverage by year (all files)\n")
    sy = Counter()
    for p in P:
        for (s, y), n in p["sat_year"].items():
            sy[(p["sensor"], s, y)] += n
    years = sorted({k[2] for k in sy if pd.notna(k[2])})
    sats = sorted({(k[0], k[1]) for k in sy})
    L.append("| sensor | satellite | " + " | ".join(str(int(y)) for y in years) + " |")
    L.append("|---|---|" + "---|" * len(years))
    for sen, s in sats:
        L.append(f"| {sen} | `{s}` | " + " | ".join(f"{sy.get((sen, s, y), 0):,}" for y in years) + " |")
    L.append("")
    # months with no detections inside each satellite's range (missing file vs real gap)
    L.append("## Months with no detections inside a satellite's range\n")
    L.append("(Per file. The pipeline's own gap warning gives the per-satellite version.)\n")
    for p in P:
        full = pd.period_range(min(p["months"]), max(p["months"]), freq="M")
        miss = [str(m) for m in full if m not in p["months"]]
        L.append(f"- {p['path']}: {len(miss)} empty month(s) {miss[:8]}")
    L.append("")
    # cross-file duplicates inside the same sensor
    L.append("## Overlap between files of the same sensor (possible NRT + archive duplicates)\n")
    any_ov = False
    for i in range(len(P)):
        for j in range(i + 1, len(P)):
            if P[i]["sensor"] == P[j]["sensor"]:
                n = len(np.intersect1d(P[i]["hashes"], P[j]["hashes"]))
                if n:
                    any_ov = True
                    L.append(f"- {P[i]['path']} and {P[j]['path']} share {n:,} identical detections (same lat, lon, date, time)")
    if not any_ov:
        L.append("- none found")
    L.append("")
    # assumption checks
    def chk(ok, msg): checks.append(("PASS" if ok else "FAIL", msg))
    for p in P:
        miss = [c for c in EXPECTED_CORE if c not in p["cols"]]
        chk(not miss, f"{p['path']}: expected columns present" + (f" (missing {miss})" if miss else ""))
        conf = set(p["cats"].get("confidence", {}))
        if p["sensor"] == "MODIS":
            chk(all(re.fullmatch(r"\d+", c) for c in conf), f"{p['path']}: MODIS confidence is numeric")
        elif p["sensor"] == "VIIRS":
            low = {c.lower() for c in conf}
            chk(low <= {"low", "nominal", "high", "l", "n", "h"}, f"{p['path']}: VIIRS confidence is low/nominal/high or l/n/h (saw {sorted(conf)[:6]})")
        sats = {s.upper() for s in p["cats"].get("satellite", {})}
        chk(sats <= KNOWN_SATELLITES, f"{p['path']}: satellite codes all known to the loader (saw {sorted(sats)})")
        chk(p["time_bad"] == 0, f"{p['path']}: acq_time format recognised")
        if "type" in p["cols"]:
            checks.append(("INFO", f"{p['path']}: `type` values {top(p['cats']['type'])}. Confirm 0 means presumed vegetation fire."))
        else:
            checks.append(("INFO", f"{p['path']}: no `type` column (loader defaults to 0)"))
        chk(p["nulls"].get("frp", 0) == 0, f"{p['path']}: no missing FRP")
    L.append("## Checks against assumptions\n")
    L += [f"- **{s}** {m}" for s, m in checks]
    out = "\n".join(L)
    print(out)
    if a.out:
        open(a.out, "w").write(out + "\n")
        print(f"\nwrote {a.out}", file=sys.stderr)


if __name__ == "__main__":
    main()